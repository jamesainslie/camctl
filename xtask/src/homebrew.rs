//! The Homebrew cask (the app) and formula (the CLI) for a release, written
//! into the yaklabco/homebrew-tap clone given to `cargo xtask homebrew`.
//!
//! camctl's repository is private, so both download through the tap's
//! `GitHubPrivateRepositoryReleaseDownloadStrategy`, which reads
//! `HOMEBREW_GITHUB_API_TOKEN`.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use semver::Version;

/// Releases are built on Apple silicon only.
const ARCH: &str = "arm64";

/// The app's release archive.
pub fn app_archive(version: &Version) -> String {
    format!("camctl-{version}-macos-{ARCH}.zip")
}

/// The CLI's release archive.
pub fn cli_archive(version: &Version) -> String {
    format!("camctl-cli-{version}-macos-{ARCH}.tar.gz")
}

/// The SHA-256 of `file` in a `shasum -a 256` listing.
pub fn sha256_for<'a>(sums: &'a str, file: &str) -> Result<&'a str> {
    let Some(sha) = sums.lines().find_map(|line| {
        let (sha, name) = line.split_once("  ")?;
        (name.trim() == file).then_some(sha)
    }) else {
        bail!("SHA256SUMS has no entry for {file}");
    };
    let valid = sha.len() == 64
        && sha
            .chars()
            .all(|c| c.is_ascii_hexdigit() && !c.is_ascii_uppercase());
    if !valid {
        bail!("SHA256SUMS has a malformed checksum for {file}: {sha}");
    }
    Ok(sha)
}

/// The cask: the app, from the release zip, with the CLI formula as a
/// dependency.
pub fn cask(version: &Version, sha256: &str) -> String {
    format!(
        r#"# typed: false
# frozen_string_literal: true

# Generated by `cargo xtask homebrew` in jamesainslie/camctl. Do not edit.
require_relative "../custom_download_strategy"

cask "camctl" do
  version "{version}"
  sha256 "{sha256}"

  url "https://github.com/jamesainslie/camctl/releases/download/v#{{version}}/camctl-#{{version}}-macos-{ARCH}.zip",
      using: GitHubPrivateRepositoryReleaseDownloadStrategy
  name "camctl"
  desc "Menu bar app for PTZ webcams: live preview, pan, tilt and zoom"
  homepage "https://github.com/jamesainslie/camctl"

  livecheck do
    skip "Updated by camctl's release workflow"
  end

  depends_on arch: :{ARCH}
  depends_on macos: :sonoma
  depends_on formula: "yaklabco/tap/camctl-cli"

  app "camctl.app"

  # No login_item here: upgrades run uninstall directives too, and the
  # login item points at the same path across versions.
  uninstall quit: "us.ainslies.camctl"

  zap trash: "~/Library/Logs/camctl"
end
"#
    )
}

/// The formula: the `camctl` CLI, from the release tarball.
pub fn formula(version: &Version, sha256: &str) -> String {
    let archive = cli_archive(version);
    format!(
        r##"# typed: false
# frozen_string_literal: true

# Generated by `cargo xtask homebrew` in jamesainslie/camctl. Do not edit.
require_relative "../custom_download_strategy"

class CamctlCli < Formula
  desc "Control UVC cameras from the shell: zoom, pan, tilt, exposure and more"
  homepage "https://github.com/jamesainslie/camctl"
  url "https://github.com/jamesainslie/camctl/releases/download/v{version}/{archive}",
      using: GitHubPrivateRepositoryReleaseDownloadStrategy
  version "{version}"
  sha256 "{sha256}"
  license "MIT"

  depends_on arch: :{ARCH}
  depends_on :macos

  def install
    bin.install "camctl"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/camctl --version")
  end
end
"##
    )
}

/// Write both files into the tap clone at `tap`, from the release's
/// `SHA256SUMS`. Returns the paths written.
pub fn write(tap: &Path, version: &Version, sums: &str) -> Result<[PathBuf; 2]> {
    if !version.pre.is_empty() {
        bail!("{version} is a pre-release; the tap carries stable releases only");
    }
    if !tap.join("custom_download_strategy.rb").is_file() {
        bail!(
            "{} is not a clone of yaklabco/homebrew-tap (no custom_download_strategy.rb)",
            tap.display()
        );
    }
    let cask_path = tap.join("Casks").join("camctl.rb");
    let formula_path = tap.join("Formula").join("camctl-cli.rb");
    // Both checksums first, so a bad listing writes nothing.
    let app = sha256_for(sums, &app_archive(version))?;
    let cli = sha256_for(sums, &cli_archive(version))?;
    for (path, text) in [
        (&cask_path, cask(version, app)),
        (&formula_path, formula(version, cli)),
    ] {
        let dir = path.parent().context("no parent directory")?;
        std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
        std::fs::write(path, text).with_context(|| format!("writing {}", path.display()))?;
    }
    Ok([cask_path, formula_path])
}

